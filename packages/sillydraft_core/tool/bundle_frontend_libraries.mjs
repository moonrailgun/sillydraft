// Rebuild in the core package: node tool/bundle_frontend_libraries.mjs.
// Versions follow 酒馆助手 a0f3a180.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtemp, mkdir, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const temporary = await realpath(await mkdtemp(join(tmpdir(), 'sillydraft-libraries-')));
const output = new URL('../lib/src/html/vendor/', import.meta.url);
async function writeBundle(name, constant, script, notice) {
  assert(!script.includes("'''"), 'Dart raw string terminator in bundle');
  assert(!/<\/script/i.test(script), 'HTML script terminator in bundle');
  await writeFile(new URL(`${name}.dart`, output),
    '// Generated by tool/bundle_frontend_libraries.mjs; do not edit.\n' +
    `// ${notice}\nconst ${constant} = r'''\n${script.trim()}\n''';\n`);
  console.log(`Wrote ${name}.dart (${Buffer.byteLength(script)} bytes of JavaScript)`);
}
try {
  execFileSync('npm', [
    'install', '--prefix', temporary, '--no-save', '--package-lock=false',
    '--ignore-scripts', '--no-audit', '--no-fund',
    'zod@4.4.3', 'yaml@2.9.1', '@tailwindcss/browser@4.1.12',
    'esbuild@0.25.11',
  ], { stdio: 'inherit' });
  const require = createRequire(join(temporary, 'package.json'));
  const { build } = require('esbuild');
  const defaults = {
    bundle: true, format: 'iife', platform: 'browser', target: 'es2020',
    minify: true, legalComments: 'inline', write: false,
  };
  await mkdir(output, { recursive: true });
  for (const [name, version, globalName, constant, licenseFile] of [
    ['zod', '4.4.3', 'z', 'frontendZodJs', 'LICENSE'],
    ['yaml', '2.9.1', 'YAML', 'frontendYamlJs', 'LICENSE'],
  ]) {
    const result = await build({ ...defaults,
      stdin: { contents: `export * from '${name}';`, resolveDir: temporary }, globalName,
    });
    const license = await readFile(join(temporary, 'node_modules', name, licenseFile), 'utf8');
    await writeBundle(name, constant, `/*! ${name} ${version}\n${license.trim()}\n*/\n${result.outputFiles[0].text}`, `${name} ${version}; license retained below.`);
  }
  const tailwind = await readFile(join(temporary, 'node_modules/@tailwindcss/browser/dist/index.global.js'), 'utf8');
  const tailwindLicense = await readFile(join(temporary, 'node_modules/@tailwindcss/browser/LICENSE'), 'utf8');
  // Keep the official browser runtime in a callable closure to observe a new DOM after document.write.
  await writeBundle('tailwind', 'frontendTailwindJs', `/*! Tailwind CSS 4.1.12\n${tailwindLicense.trim()}\n*/\n(function(){
let observers = [], generation = 0;
window.__sdStartTailwind = function(){
  observers.forEach(observer => observer.disconnect());
  observers = [];
  const current = ++generation;
  const TrackedObserver = class extends MutationObserver {
    constructor(callback) { super(callback); observers.push(this); }
    observe(...args) { if (generation === current) super.observe(...args); }
  };
  (function(MutationObserver){${tailwind}\n})(TrackedObserver);
};
window.__sdStartTailwind();
})();`, 'Official @tailwindcss/browser 4.1.12 (MIT).');
} finally {
  await rm(temporary, { recursive: true, force: true });
}
