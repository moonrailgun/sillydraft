abstract interface class SecretStore {
  Future<String?> read(String key);
  Future<void> write(String key, String value);
  Future<void> delete(String key);
}

/// Secrets kept as plain JSON in `secrets.json` in the app's data directory.
///
/// The author chose a plain file over the platform keychain so every
/// platform stores secrets the same way and macOS stops asking for the login
/// keychain password after each rebuild. The file stays on this device:
/// project backups, sync and exports never include it, and the database
/// refuses credentials in its settings. On macOS and Linux the file is
/// readable by the owner only.
///
/// Installs that used the keychain move their secrets over once through
/// [migrateLegacy]. Until that succeeds, a key missing from the file is still
/// read from the keychain, and a refused keychain read is an error rather
/// than "no key": the resource key must never be regenerated by mistake,
/// or imported ST originals could no longer be decrypted.
final class FileSecrets implements SecretStore {
  FileSecrets(this.file, {this._legacy});
  final File file;
  final LegacySecretStore? _legacy;

  Map<String, String>? _values;

  /// Keys deleted before the keychain was migrated, so the keychain copy
  /// does not come back.
  Set<String> _deleted = {};

  /// Whether there is nothing (left) to take from the keychain; persisted.
  bool _done = false;
  bool get _migrated => _legacy == null || _done;
  Future<void> _queue = Future.value();

  Future<T> _serial<T>(Future<T> Function() task) {
    final next = _queue.then((_) => task());
    _queue = next.then((_) {}, onError: (Object _) {});
    return next;
  }

  Future<Map<String, String>> _load() async {
    if (_values case final values?) return values;
    if (!await file.exists()) return _values = {};
    final json = jsonDecode(await file.readAsString());
    if (json is! Map<String, dynamic> || json['values'] is! Map) {
      throw FormatException('本机密钥文件已损坏：${file.path}');
    }
    _done = json['migrated'] == true;
    _deleted = {...?(json['deleted'] as List?)?.cast<String>()};
    return _values = {
      for (final e in (json['values'] as Map).entries)
        e.key as String: e.value as String,
    };
  }

  Future<void> _save() async {
    await file.parent.create(recursive: true);
    final temp = File('${file.path}.tmp');
    await temp.writeAsString(
      const JsonEncoder.withIndent('  ').convert({
        'version': 1,
        'migrated': _migrated,
        if (_deleted.isNotEmpty) 'deleted': _deleted.toList()..sort(),
        'values': _values,
      }),
      flush: true,
    );
    if (Platform.isMacOS || Platform.isLinux) {
      try {
        await Process.run('chmod', ['600', temp.path]);
      } on ProcessException {
        // Best effort: the data directory is already private to the user.
      }
    }
    await temp.rename(file.path);
  }

  @override
  Future<String?> read(String key) => _serial(() async {
    final values = await _load();
    final value = values[key];
    if (value != null || _migrated || _deleted.contains(key)) return value;
    final legacy = await _legacy!.read(key);
    if (legacy != null) {
      values[key] = legacy;
      await _save();
    }
    return legacy;
  });

  @override
  Future<void> write(String key, String value) => _serial(() async {
    (await _load())[key] = value;
    _deleted.remove(key);
    await _save();
  });

  @override
  Future<void> delete(String key) => _serial(() async {
    (await _load()).remove(key);
    if (_migrated) return _save();
    _deleted.add(key);
    await _save();
    try {
      await _legacy!.delete(key);
    } catch (_) {
      // The tombstone above already keeps the keychain copy from returning.
    }
  });

  /// Copies everything the keychain holds into the file once, then clears
  /// the keychain. Throws when the keychain refuses (for example the author
  /// denied the macOS prompt); the next launch tries again.
  Future<void> migrateLegacy() => _serial(() async {
    final values = await _load();
    if (_migrated) return;
    final legacy = await _legacy!.readAll();
    for (final e in legacy.entries) {
      if (!values.containsKey(e.key) && !_deleted.contains(e.key)) {
        values[e.key] = e.value;
      }
    }
    _done = true;
    _deleted = {};
    await _save();
    try {
      await _legacy.deleteAll();
    } catch (_) {
      // Stale keychain copies are never read again once migrated.
    }
  });
}

/// The keychain-style store secrets used to live in; read only to migrate.
abstract interface class LegacySecretStore implements SecretStore {
  Future<Map<String, String>> readAll();
  Future<void> deleteAll();
}

/// The platform keychain / keystore, as earlier versions configured it.
final class KeychainSecrets implements LegacySecretStore {
  final _storage = Platform.isMacOS
      ? const FlutterSecureStorage(
          mOptions: MacOsOptions(usesDataProtectionKeychain: false),
        )
      : const FlutterSecureStorage();
  @override
  Future<String?> read(String key) => _storage.read(key: key);
  @override
  Future<void> write(String key, String value) =>
      _storage.write(key: key, value: value);
  @override
  Future<void> delete(String key) => _storage.delete(key: key);
  @override
  Future<Map<String, String>> readAll() => _storage.readAll();
  @override
  Future<void> deleteAll() => _storage.deleteAll();
}

/// For isolated tests only. The app itself always uses [FileSecrets].
final class MemorySecrets implements SecretStore {
  final _values = <String, String>{};
  @override
  Future<String?> read(String key) async => _values[key];
  @override
  Future<void> write(String key, String value) async {
    _values[key] = value;
  }

  @override
  Future<void> delete(String key) async {
    _values.remove(key);
  }
}

final class AppServices {
  AppServices({
    required this.repository,
    required this.secrets,
    this.dataDirectory,
    this.updateEndpoint,
    ProviderFactory? modelProviderFactory,
    ImageProviderFactory? imageProviderFactory,
  }) : remote = null,
       _modelProviderFactory = modelProviderFactory {
    assets = dataDirectory == null
        ? null
        : AssetLibrary(
            repository: repository,
            directory: Directory('${dataDirectory!.path}/assets'),
          );
    runner = TaskRunner(
      repository: repository,
      providerFactory: modelProviderFactory ?? provider,
      imageProviderFactory: imageProviderFactory ?? imageProvider,
      assetLibrary: assets,
    );
    library = ResourceLibrary(repository: repository, keyProvider: resourceKey);
    _wire();
  }

  /// A paired desktop's library over [session]: its database, tasks, files
  /// and models. [secrets] stays this device's own; files are cached under
  /// [cache].
  AppServices.remote(
    RemoteSession session, {
    required this.secrets,
    required Directory cache,
    this.updateEndpoint,
  }) : repository = session.repository,
       remote = session,
       dataDirectory = null,
       _modelProviderFactory = null {
    assets = AssetLibrary(
      repository: repository,
      directory: Directory('${cache.path}/assets'),
      mirror: HttpAssetMirror(session),
    );
    runner = RemoteTaskControl(
      session,
      providerFactory: provider,
      imageProviderFactory: imageProvider,
      assetLibrary: assets,
    );
    library = ResourceLibrary(
      repository: repository,
      keyProvider: () async => session.hello.resourceKey,
    );
    _wire();
  }

  void _wire() {
    writing = WritingService(repository: repository, runner: runner);
    sidecar = SidecarAgent(repository: repository, runner: runner);
    editor = EditorAgent(repository: repository, runner: runner);
    illustrations = IllustrationService(repository: repository, runner: runner);
    personas = PersonaService(repository: repository, runner: runner);
  }

  final StoryRepository repository;
  final SecretStore secrets;
  final Directory? dataDirectory;

  /// The desktop this library belongs to; null for this device's own.
  final RemoteSession? remote;

  /// Sharing this library with phones, and handing out share codes.
  late final hosting = LibraryHosting(this);

  /// Where update checks ask for the latest release; null turns them off
  /// (tests, and iOS, which has no published package).
  final Uri? updateEndpoint;
  late final TaskControl runner;
  late final WritingService writing;
  late final SidecarAgent sidecar;
  late final EditorAgent editor;
  late final ResourceLibrary library;
  late final AssetLibrary? assets;
  late final IllustrationService illustrations;
  late final PersonaService personas;
  SkillLibrary get skills => SkillLibrary(repository);
  ProjectBackup get backups => ProjectBackup(
    repository: repository,
    assets: assets ?? (throw StateError('本地资源目录尚未就绪')),
    resources: library,
  );
  PublicationExporter get publications => PublicationExporter(
    repository: repository,
    assets: assets ?? (throw StateError('本地资源目录尚未就绪')),
  );
  Future<List<int>>? _keyFuture;
  Future<List<int>> resourceKey() => _keyFuture ??= _loadResourceKey();
  Future<List<int>> _loadResourceKey() async {
    try {
      final existing = await secrets.read('resources/aes256');
      if (existing != null) return base64Decode(existing);
      final random = Random.secure();
      final key = List.generate(32, (_) => random.nextInt(256));
      await secrets.write('resources/aes256', base64Encode(key));
      return key;
    } catch (_) {
      _keyFuture = null;
      rethrow;
    }
  }

  final _drafts = <Object, Future<void> Function()>{};

  static Future<AppServices> open({bool checkUpdates = true}) async {
    final dir = await getApplicationSupportDirectory();
    await dir.create(recursive: true);
    final secretsFile = File('${dir.path}/secrets.json');
    // A brand-new install has nothing in the keychain to move, so it never
    // touches the keychain (or needs a desktop keyring) at all.
    final fresh =
        !File('${dir.path}/library.sqlite').existsSync() &&
        !secretsFile.existsSync();
    final secrets = FileSecrets(
      secretsFile,
      legacy: fresh ? null : KeychainSecrets(),
    );
    try {
      await secrets.migrateLegacy();
    } catch (e) {
      // Keys still in the keychain are read on demand; retried next launch.
      stderr.writeln('SillyDraft: keychain migration postponed: $e');
    }
    final services = AppServices(
      repository: StoryRepository.open('${dir.path}/library.sqlite'),
      secrets: secrets,
      dataDirectory: dir,
      updateEndpoint: checkUpdates && !Platform.isIOS ? latestReleaseUrl : null,
    );
    await services.runner.recoverInterrupted();
    // A desktop shares its library again when the author left it on.
    if (desktopPlatform) unawaited(services.hosting.restore());
    try {
      await services.repository.migrateLegacyPersonas();
    } catch (e) {
      // Unmigrated profiles read as “我” until the next launch retries.
      stderr.writeln('SillyDraft: persona migration postponed: $e');
    }
    try {
      await services.assets?.pruneOrphans();
    } catch (e) {
      // Maintenance failure must not prevent access to saved manuscripts.
      stderr.writeln(
        'SillyDraft: unused asset cleanup failed; will retry on next launch: $e',
      );
    }
    return services;
  }

  final ProviderFactory? _modelProviderFactory;

  /// A provider for a connection that may not be saved yet, such as the one
  /// being edited: [secret] is the key typed into the form, if any.
  Future<ModelProvider> draftProvider(
    ModelConnection connection, {
    String? secret,
  }) async {
    if (remote != null) throw StateError('连接在桌面管理');
    if (!connection.supportsText) {
      throw const FormatException('此连接仅支持生图，请选择文本模型');
    }
    final factory = _modelProviderFactory;
    if (factory != null) return factory(connection);
    if (connection.protocol.isLocalCli) {
      return LocalCliProvider(config: connection);
    }
    final key = secret ?? await savedKey(connection);
    return connection.protocol == ModelProtocol.sillyDraftRunner
        ? RemoteModelProvider(config: connection, accessToken: key)
        : OpenAICompatibleProvider(config: connection, apiKey: key);
  }

  Future<ModelProvider> provider(ModelConnection connection) async {
    if (remote case final session?) {
      return DesktopModelProvider(session, connection);
    }
    await _checkEndpoint(connection);
    if (connection.protocol.isLocalCli) {
      return LocalCliProvider(config: connection);
    }
    if (connection.protocol == ModelProtocol.sillyDraftRunner) {
      // Image tasks also use this adapter to confirm remote cancellation.
      return RemoteModelProvider(
        config: connection,
        accessToken: await secrets.read('model/${connection.id}') ?? '',
      );
    }
    if (!connection.supportsText) {
      throw const FormatException('此连接仅支持生图，请选择文本模型');
    }
    if (connection.protocol != ModelProtocol.openAICompatible) {
      throw const FormatException('当前版本支持 OpenAI 兼容接口，请使用兼容端点');
    }
    return OpenAICompatibleProvider(
      config: connection,
      apiKey: await secrets.read('model/${connection.id}') ?? '',
    );
  }

  Future<ImageProvider> imageProvider(ModelConnection connection) async {
    if (!connection.supportsImages) {
      throw const FormatException('此连接仅支持文本，请选择生图模型');
    }
    if (remote case final session?) {
      return DesktopImageProvider(session, connection);
    }
    await _checkEndpoint(connection);
    final key = await secrets.read('model/${connection.id}') ?? '';
    if (connection.protocol == ModelProtocol.comfyUI) {
      return ComfyUIProvider(config: connection, apiKey: key);
    }
    if (connection.protocol == ModelProtocol.novelAI) {
      return NovelAIImageProvider(config: connection, apiKey: key);
    }
    if (connection.protocol == ModelProtocol.sillyDraftRunner) {
      return RemoteImageProvider(config: connection, accessToken: key);
    }
    return OpenAIImageProvider(config: connection, apiKey: key);
  }

  /// Set once this library was first shared: from then on a connection
  /// without an endpoint record was not saved here. Kept outside the
  /// `endpoint/<id>` namespace, which connection ids from phones reach.
  static const _bound = 'remote/endpoints-bound';

  /// Refuses [connection] when it points somewhere other than where this
  /// device saved it: paired phones can rewrite the shared `connections`
  /// setting, not this device's secrets file, and keys and local tools go
  /// only to endpoints the author saved here. Connections saved before
  /// endpoints were recorded pass until the library is first shared.
  Future<void> _checkEndpoint(ModelConnection connection) async {
    if (!await endpointTrusted(connection)) {
      throw StateError('连接地址与本机保存的不一致，已拒绝使用密钥');
    }
  }

  /// Whether [connection] points where this device saved it (see
  /// [_checkEndpoint]), so its saved key may go there.
  Future<bool> endpointTrusted(ModelConnection connection) async {
    final saved = await secrets.read('endpoint/${connection.id}');
    if (saved == null) return await secrets.read(_bound) == null;
    final endpoint = jsonDecode(saved) as Map<String, dynamic>;
    return connectionEndpointKeys.every(
      (k) => endpoint[k] == connection.raw[k],
    );
  }

  /// Why the settings editor holds a saved key back.
  static const movedEndpoint = '连接地址已在本机之外改动，请重新输入密钥';

  /// The key saved for [connection], for the settings editor and its share
  /// code: refused while [connection] points elsewhere than where the key
  /// was saved, as after a phone rewrote it. No saved key is no secret.
  Future<String> savedKey(ModelConnection connection) async {
    final key = await secrets.read('model/${connection.id}');
    if (key == null || key.isEmpty) return '';
    if (!await endpointTrusted(connection)) throw StateError(movedEndpoint);
    return key;
  }

  Future<void> _bindEndpoint(ModelConnection connection) => secrets.write(
    'endpoint/${connection.id}',
    jsonEncode({for (final k in connectionEndpointKeys) k: connection.raw[k]}),
  );

  /// Records every saved connection's endpoint before this library is first
  /// shared, when nothing but this device can have written them. Later
  /// shares skip it, so a connection a phone added stays refused.
  Future<void> bindSavedEndpoints() async {
    if (await secrets.read(_bound) != null) return;
    for (final connection in await connections()) {
      if (await secrets.read('endpoint/${connection.id}') == null) {
        await _bindEndpoint(connection);
      }
    }
    await secrets.write(_bound, 'true');
  }

  /// A phone's list leaves out the desktop's local subscriptions, which
  /// run only there (see [RemoteHost]).
  Future<List<ModelConnection>> connections() async {
    final setting = await repository.getSetting('connections');
    return (setting?['items'] as List? ?? [])
        .map((v) => ModelConnection.fromJson(v as Map<String, dynamic>))
        .where((c) => remote == null || !c.protocol.isLocalCli)
        .toList();
  }

  Future<void> saveConnection(
    ModelConnection connection, {
    String? apiKey,
  }) async {
    if (remote != null) throw StateError('连接在桌面管理');
    // The key follows a new address only when typed again: the form may
    // hold an address a phone wrote. savedKey refuses for us.
    if (apiKey == null && !connection.protocol.isLocalCli) {
      await savedKey(connection);
    }
    if (apiKey != null) await secrets.write('model/${connection.id}', apiKey);
    await _bindEndpoint(connection);
    final list = await connections();
    list.removeWhere((c) => c.id == connection.id);
    list.add(connection);
    await repository.setSetting('connections', {
      'items': list.map((c) => c.raw).toList(),
    });
  }

  Future<void> removeConnection(String id) async {
    if (remote != null) throw StateError('连接在桌面管理');
    final list = await connections();
    list.removeWhere((c) => c.id == id);
    await repository.setSetting('connections', {
      'items': list.map((c) => c.raw).toList(),
    });
    await secrets.delete('model/$id');
    await secrets.delete('endpoint/$id');
  }

  Future<ModelConnection?> connectionFor(String role) async {
    final all = (await connections())
        .where((c) => connectionServes(c, role))
        .toList();
    if (all.isEmpty) return null;
    final roles = await repository.getSetting('modelRoles');
    final connection =
        all.where((c) => c.id == roles?[role]).firstOrNull ?? all.first;
    final model = roles?['${role}Model'];
    return connection.id == roles?[role] && connection.models.contains(model)
        ? connection.withModel(model as String)
        : connection;
  }

  void registerDraft(Object owner, Future<void> Function() flush) =>
      _drafts[owner] = flush;
  void unregisterDraft(Object owner) => _drafts.remove(owner);
  Future<void> flushDrafts() async {
    for (final flush in _drafts.values.toList()) {
      await flush();
    }
  }

  /// Shuts this library down, saving open drafts first unless
  /// [flushDrafts] is false. Drafts that cannot be saved still let it shut
  /// down, and their error follows.
  Future<void> close({bool flushDrafts = true}) async {
    try {
      if (flushDrafts) await this.flushDrafts();
    } finally {
      await hosting.stop();
      await runner.close();
      if (remote case final session?) {
        await session.close();
      } else {
        await repository.close();
      }
    }
  }
}

final servicesProvider = Provider<AppServices>(
  (ref) => throw StateError('AppServices not initialized'),
);
final repositoryProvider = Provider<StoryRepository>(
  (ref) => ref.watch(servicesProvider).repository,
);
final repositoryChangesProvider = StreamProvider<int>((ref) {
  // Riverpod compares stream values. Repeated void/null events are equal and
  // would leave query providers cached after the first database change.
  var revision = 0;
  return ref.watch(repositoryProvider).changes.map((_) => ++revision);
});

/// [repositoryChangesProvider] minus writes that touch only generation tasks,
/// which a streamed chapter makes a few times a second, for views that never
/// read tasks.
final repositoryContentChangesProvider = StreamProvider<int>((ref) {
  var revision = 0;
  return ref.watch(repositoryProvider).contentChanges.map((_) => ++revision);
});
final novelsProvider = FutureProvider<List<Novel>>((ref) {
  ref.watch(repositoryContentChangesProvider);
  return ref.watch(repositoryProvider).listNovels(includeArchived: true);
});
final storyProvider = FutureProvider.family<StorySnapshot, String>((
  ref,
  branchId,
) {
  ref.watch(repositoryContentChangesProvider);
  return ref.watch(repositoryProvider).getStory(branchId);
});
final settingProvider = FutureProvider.family<Map<String, dynamic>?, String>((
  ref,
  key,
) {
  ref.watch(repositoryContentChangesProvider);
  return ref.watch(repositoryProvider).getSetting(key);
});

/// The connection a model role uses, or null while none is configured.
final roleConnectionProvider = FutureProvider.family<ModelConnection?, String>((
  ref,
  role,
) {
  ref.watch(repositoryContentChangesProvider);
  return ref.watch(servicesProvider).connectionFor(role);
});

/// The editor also needs tool calls: OpenAI-compatible or a local CLI.
bool connectionServes(ModelConnection connection, String role) =>
    switch (role) {
      'editor' =>
        connection.supportsText &&
            (connection.protocol == ModelProtocol.openAICompatible ||
                connection.protocol.isLocalCli),
      'image' => connection.supportsImages,
      _ => connection.supportsText,
    };

/// macOS, Windows or Linux: hosts a library for phones and runs local CLIs.
bool get desktopPlatform =>
    Platform.isMacOS || Platform.isWindows || Platform.isLinux;

/// Local subscriptions run an installed command-line tool: desktop only.
bool get localCliAvailable => desktopPlatform;
